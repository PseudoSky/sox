def _fmt(v: float, unit: str = "") -> str:
    a = abs(v)
    if a >= 1e9:
        s = f"{v / 1e9:.2f}B"
    elif a >= 1e6:
        s = f"{v / 1e6:.2f}M"
    elif a >= 1e3:
        s = f"{v / 1e3:.1f}k"
    elif a >= 10:
        s = f"{v:.1f}"
    elif a >= 1:
        s = f"{v:.3f}"
    else:
        s = f"{v:.5f}"
    return s + unit


def format_provenance(ds: Optional[EventDataset] = None) -> str:
    ds = ds or dataset()
    p = ds.provenance
    lines = ["=" * 72]
    lines.append("EVENT-DATA CALIBRATION (agent-dashboard event stream, "
                 "READ-ONLY)")
    lines.append(f"source: {p.get('source')}  (schema v{p.get('schema_version')})")
    lines.append(
        f"  {int(p.get('event_count', 0)):,} event rows · "
        f"${float(p.get('total_cost_usd', 0)):,.2f} billed · "
        f"{int(p.get('total_dispatches', 0)):,} dispatches · "
        f"{int(p.get('total_steps', 0)):,} steps · "
        f"{int(p.get('total_tool_calls', 0)):,} tool calls"
    )
    lines.append(
        f"  window {p.get('span_days')} days · "
        f"{len(ds.agents)} agents (>= {MIN_SESSIONS} runs) · "
        f"{len(ds.tasks)} top tasks"
    )
    lines.append(f"  unit: {UNIT_CAVEAT}")
    lines.append("=" * 72)
    return "\n".join(lines)


def agent_rows(ds: Optional[EventDataset] = None,
               limit: Optional[int] = None) -> List[Dict[str, object]]:
    """The per-agent extracted table (mean per-run profile + cold start)."""
    ds = ds or dataset()
    order = sorted(ds.agents.values(), key=lambda p: -p.mean["cost_usd"])
    if limit:
        order = order[:limit]
    out: List[Dict[str, object]] = []
    for p in order:
        out.append({
            "agent": p.agent,
            "runs": p.sessions,
            "cost/run $": p.mean["cost_usd"],
            "in/run": p.mean["tokens_in"],
            "out/run": p.mean["tokens_out"],
            "reason/run": p.mean["tokens_reasoning"],
            "cache/run": p.mean["tokens_cache_read"],
            "steps/run": p.mean["steps"],
            "seconds/run": p.mean["active_ms"] / 1000.0,
            "tools/run": p.mean["tool_calls"],
            "cold-start prompt": p.cold_start_prompt,
            "cold-start $": p.cold_start_cost,
        })
    return out


def task_rows(ds: Optional[EventDataset] = None,
              limit: Optional[int] = None) -> List[Dict[str, object]]:
    """The per-task extracted table (aggregate per task label)."""
    ds = ds or dataset()
    order = sorted(ds.tasks.items(), key=lambda kv: -kv[1]["cost_usd"])
    if limit:
        order = order[:limit]
    out: List[Dict[str, object]] = []
    for name, v in order:
        out.append({
            "task": name,
            "rows": v.get("rows"),
            "cost $": v["cost_usd"],
            "in": v["tokens_in"],
            "out": v["tokens_out"],
            "reason": v["tokens_reasoning"],
            "cache_read": v["tokens_cache_read"],
            "steps": v["steps"],
            "seconds": v["active_ms"] / 1000.0,
            "tool_calls": v["tool_calls"],
        })
    return out


def op_rows(ds: Optional[EventDataset] = None) -> List[Dict[str, object]]:
    """The per-operation calibrated table (op -> real agents -> per-fire cost)."""
    ds = ds or dataset()
    out: List[Dict[str, object]] = []
    for op in OP_AGENTS:
        prof = ds.op_profile(op)
        if prof is None:
            continue
        out.append({
            "op": op,
            "agents": ", ".join(prof.agents),
            "in": prof.in_tok,
            "out": prof.out_tok,
            "reason": prof.reasoning_tok,
            "cache_read": prof.cache_read_tok,
            "$/fire": prof.cost_usd,
            "seconds": prof.seconds,
            "tools": prof.tool_calls,
            "cold-start $": prof.cold_start_cost,
            "fallback": prof.fallback,
        })
    return out


def _table(rows: Sequence[Mapping[str, object]],
           columns: Sequence[Tuple[str, str]], title: str) -> str:
    lines = [title]
    header = " ".join(f"{label:>{width}}" for label, width in columns)
    lines.append(header)
    lines.append("-" * len(header))
    for r in rows:
        cells = []
        for key, width in columns:
            v = r.get(key)
            if isinstance(v, float):
                cells.append(f"{_fmt(v):>{width}}")
            else:
                cells.append(f"{str(v):>{width}}")
        lines.append(" ".join(cells))
    return "\n".join(lines)


def format_agent_table(ds: Optional[EventDataset] = None,
                       limit: int = 24) -> str:
    rows = agent_rows(ds, limit=limit)
    return _table(rows, (
        ("agent", 22), ("runs", 6), ("cost/run $", 11), ("in/run", 8),
        ("out/run", 8), ("reason/run", 10), ("cache/run", 10),
        ("seconds/run", 12), ("tools/run", 10), ("cold-start prompt", 18),
    ), f"PER-AGENT PROFILES (top {limit} by cost; mean per real agent run)")


def format_task_table(ds: Optional[EventDataset] = None,
                      limit: int = 16) -> str:
    rows = task_rows(ds, limit=limit)
    return _table(rows, (
        ("task", 40), ("rows", 6), ("cost $", 9), ("in", 8), ("out", 8),
        ("cache_read", 11), ("steps", 7), ("seconds", 9), ("tool_calls", 11),
    ), f"PER-TASK PROFILES (top {limit} by cost; aggregate per task label)")


def format_op_table(ds: Optional[EventDataset] = None) -> str:
    rows = op_rows(ds)
    return _table(rows, (
        ("op", 15), ("agents", 30), ("in", 8), ("out", 7), ("reason", 8),
        ("cache_read", 11), ("$/fire", 10), ("seconds", 9), ("tools", 7),
        ("cold-start $", 13),
    ), "PER-OPERATION CALIBRATION (op -> real agents -> measured per-fire)")


def format_distributions(ds: Optional[EventDataset] = None) -> str:
    """The per-agent / per-task / per-event distribution table (p50/p90/mean)."""
    ds = ds or dataset()
    lines = ["=" * 72]
    lines.append("EVENT DISTRIBUTIONS (p50 / p90 / mean / count)")
    lines.append("-" * 72)
    for label, dist, unit in (
        ("PER AGENT (one obs / agent, n=" + str(len(ds.agents)) + ")",
         ds.agent_dist, "per agent total"),
        ("PER TASK (one obs / task label)", ds.task_dist, "per task total"),
        ("PER EVENT ROW", ds.per_event, "per recorded row"),
    ):
        lines.append(f"{label}   [{unit}]")
        lines.append(f"    {'metric':<18}{'p50':>13}{'p90':>13}{'mean':>13}"
                     f"{'count':>8}")
        for m in EVENT_METRICS:
            q = dist.get(m)
            if q is None:
                continue
            lines.append(
                f"    {m:<18}{_fmt(q.p50):>13}{_fmt(q.p90 or 0.0):>13}"
                f"{_fmt(q.mean or 0.0):>13}{(q.count or 0):>8}"
            )
        lines.append("-" * 72)
    lines.append("=" * 72)
    return "\n".join(lines)


def format_event_report(ds: Optional[EventDataset] = None) -> str:
    """The full extraction report: provenance + agents + tasks + ops + dists."""
    ds = ds or dataset()
    return "\n\n".join((
        format_provenance(ds),
        format_op_table(ds),
        format_agent_table(ds),
        format_task_table(ds),
        format_distributions(ds),
    ))


def composition_rows(ds: Optional[EventDataset] = None) -> List[Dict[str, float]]:
    """The event stream's real 4-class LLM cost composition (input/output/...)."""
    ds = ds or dataset()
    p = ds.provenance
    toks = p.get("total_tokens", {})
    classes = {
        "input": float(toks.get("tokens_in", 0)) * P_IN,
        "output": float(toks.get("tokens_out", 0)) * P_OUT,
        "reasoning": float(toks.get("tokens_reasoning", 0)) * P_OUT,
        "cache_read": float(toks.get("tokens_cache_read", 0)) * P_CACHE_READ,
    }
    total = sum(classes.values()) or 1.0
    return [{"class": k, "usd": v, "share": v / total}
            for k, v in classes.items()]
