def dispatched_agents() -> Tuple[str, ...]:
    """The union of real agents that an op dispatch may start."""
    seen: List[str] = []
    for agents in OP_AGENTS.values():
        for a in agents:
            if a not in seen:
                seen.append(a)
    return tuple(seen)


def calibrated_c_dispatch(ds: Optional[EventDataset] = None) -> float:
    """The event-calibrated fresh-agent dispatch cost (per-agent cold start)."""
    ds = ds or dataset()
    agents = [a for a in dispatched_agents() if a in ds.agents]
    if not agents:
        return 0.0
    return statistics.fmean(ds.agents[a].cold_start_cost for a in agents)


def calibrated_OC(ds: Optional[EventDataset] = None) -> float:
    """The event-calibrated per-tool-call cost (result-payload token proxy).

    The store reports tool result sizes in characters, not tokens; the measured
    ``sum(result_chars) / tool_calls / 4`` payload is ``$0.0001418`` -- within
    1 % of the prior opencode.db measurement ($0.000143), so the two agree.
    """
    ds = ds or dataset()
    prov = ds.provenance
    calls = float(prov.get("total_tool_calls", 0) or 0)
    if calls <= 0:
        return 0.0
    payload_tokens = float(prov.get("sum_result_chars", 0) or 0) / CHARS_PER_TOKEN / calls
    return payload_tokens * P_IN


def event_calibrated(base: Optional[PipelineConfig] = None,
                     ds: Optional[EventDataset] = None,
                     unit: str = "run") -> PipelineConfig:
    """Return ``base`` recosted from the real per-agent event profiles.

    Replaces the Appendix-C placeholder per-op token estimates with the real
    per-agent profiles (and the per-agent cold-start sizes), re-derives ``c_op``
    (including the measured reasoning / cache-read classes), and records the
    explicit per-op token quad on the config so the engine's LLM-composition
    split is faithful.  Everything else on ``base`` is preserved.

    ``unit="run"`` (default) prices each op as a real agent **run**; ``unit=
    "event"`` prices it as the per-event-row **marginal operation** (the finer
    measure the task calls for).  A default config is untouched until this is
    called, so the model's existing behaviour is preserved.
    """
    if unit not in ("run", "event"):
        raise ValueError(f"unit must be 'run' or 'event', got {unit!r}")
    from dataclasses import fields as _fields

    ds = ds or dataset()
    base = base or PipelineConfig()
    tokens = base.tokens
    durations = base.durations
    c_op = base.c_op
    tok_names = {f.name for f in _fields(TaskTokens)}
    dur_names = {f.name for f in _fields(TaskDurations)}
    cost_names = {f.name for f in _fields(TaskOpCost)}
    explicit: List[Tuple[str, Tuple[float, float, float, float]]] = []
    for field_name, op in FIELD_TO_OP.items():
        prof = ds.op_profile(op, unit=unit)
        if prof is None:
            continue
        if field_name in tok_names:
            tokens = replace(tokens, **{field_name: (prof.in_tok, prof.out_tok)})
        if field_name in dur_names:
            # ``test_run`` has no static duration (it is per-AC dynamic), so a
            # profile field absent from TaskDurations is simply skipped.
            durations = replace(durations, **{field_name: prof.seconds})
        if field_name in cost_names:
            c_op = replace(c_op, **{field_name: prof.cost_usd})
    for op in ENGINE_OPS:
        prof = ds.op_profile(op, unit=unit)
        if prof is not None:
            explicit.append((op, prof.tokens))
    return replace(
        base,
        tokens=tokens,
        durations=durations,
        c_op=c_op,
        c_dispatch=calibrated_c_dispatch(ds),
        OC=calibrated_OC(ds),
        op_event_profiles=tuple(explicit),
    )


