"""Real agent-event spend calibration (the agent-dashboard event stream).

The model's Appendix-C per-operation token estimates were *placeholders* sampled
from a 5-task benchmark; the spec itself flags them LOW-CONFIDENCE (OPEN-3) and
the prior calibration pinned only two scalars (``c_dispatch`` / ``OC``) to the
operator's ``opencode.db`` medians.  This module replaces them with the **real
per-agent and per-task distributions extracted from the agent-dashboard event
stream** and drives the simulator's spend forecast from that data.

Source (real, READ-ONLY -- never modified)
------------------------------------------
``/Users/nix/dev/ai/scratch/agent-dashboard/public/events.json`` -- schema v3,
the operator's own agent telemetry.  56,840 time-bucketed event rows over ~98
days (2026-06-29 .. 2026-10-04), **$328.19** total billed spend, 4,055 agent
dispatches, 172,852 model steps and 244,324 tool calls.  The companion
``data/opencode-events.json`` (schema v2) is accepted as an alternate source;
``public/events.json`` is preferred.

Each row is a per-``(bucket, dims)`` aggregate carrying
``cost_usd`` / ``tokens_in`` / ``tokens_out`` / ``tokens_reasoning`` /
``tokens_cache_read`` / ``tokens_cache_write`` / ``steps`` / ``active_ms`` /
``tool_calls`` / ``dispatches``.  ``tokens_in`` EXCLUDES cache reads (the store's
convention), so the four billed classes are disjoint::

    cost = in*P_IN + out*P_OUT + reasoning*P_OUT + cache_read*P_CACHE_READ

Priced at the measured OFF-PEAK card (:mod:`pipeline_sim.config`) this reproduces
the stream's own ``cost_usd`` to **0.7 %** ($330.64 recomputed vs $328.19 billed)
-- the residual is rounding in the store's own per-row estimate -- which is the
cross-check that the price basis and the four-class model are correct.

What is committed vs recomputed
-------------------------------
Reading 40 MB at import (and in the Streamlit app) would be wasteful and would
make the package depend on a machine-local scratch path.  So the *extraction* is
committed as a compact snapshot (``events_snapshot.json``, generated by
:func:`build_snapshot`) and :meth:`EventDataset.from_snapshot` loads it.  The
snapshot is produced by the *same* code path as :func:`extract`, so the two agree
by construction; `tests/test_event_calibration.py` re-extracts from the source
when it is present and asserts they match.

Units -- what one "operation" is
--------------------------------
The event stream has no per-operation boundary markers, so the *per-agent run*
(one ``(session_id, agent)`` -- a dispatched task) is the calibrated unit: an
operation mapped to agent ``A`` is priced as ``A``'s **mean run profile**.
``PER_AC_DIVISOR`` splits a test agent's run across the ticket's acceptance
criteria (the model instantiates per-AC test tasks).  Both the per-agent and the
per-task distributions, the per-event (per-row) profile, and the per-agent
**cold-start** prompt sizes are extracted and surfaced; the caveat that a run is
coarser than a single small op is documented, not hidden (see
:data:`UNIT_CAVEAT`).

Additive
--------
Nothing here mutates the model.  Importing this module has no side effects:
the default :class:`~pipeline_sim.config.PipelineConfig` is unchanged and every
existing test stays green.  The event calibration is opt-in through
:func:`event_calibrated` (a pure ``PipelineConfig`` transform), the harness
``--event-calibrated`` flag and the app's toggle.
"""

