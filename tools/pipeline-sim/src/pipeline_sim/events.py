@dataclass(frozen=True)
class AgentRunProfile:
    """One real agent's measured per-run profile (mean / median / p90)."""

    agent: str
    sessions: int
    mean: Mapping[str, float]
    median: Mapping[str, float]
    p90: Mapping[str, float]
    cold_start_in: float
    cold_start_cache_read: float
    cold_start_prompt: float
    cold_start_n: int
    rows: int = 0

    def per_row(self, metric: str) -> float:
        """The agent's mean value of ``metric`` per recorded event row.

        ``event_rows`` = ``sum over rows``, so the per-row mean is the agent's
        lifetime total / its row count = ``mean run * runs / rows``.  This is the
        finer "one marginal operation" unit (vs a whole run).
        """
        if self.rows <= 0:
            return self.mean[metric]
        return self.mean[metric] * self.sessions / self.rows

    @property
    def cold_start_cost(self) -> float:
        """Measured cost of a cold start: the prompt billed at real rates.

        Fresh input at the input rate, the cached prefix at the cache-read rate.
        """
        return llm_cost(self.cold_start_in, 0.0, 0.0, self.cold_start_cache_read)


@dataclass(frozen=True)
class OpProfile:
    """One simulator operation calibrated from the real per-agent runs."""

    op: str
    agents: Tuple[str, ...]
    in_tok: float
    out_tok: float
    reasoning_tok: float
    cache_read_tok: float
    cost_usd: float
    seconds: float
    tool_calls: float
    cold_start_cost: float
    cold_start_tokens: float
    fallback: bool = False

    @property
    def tokens(self) -> Tuple[float, float, float, float]:
        return (self.in_tok, self.out_tok, self.reasoning_tok,
                self.cache_read_tok)


@dataclass(frozen=True)
class ColdStart:
    """A measured cold-start profile (system prompt + schemas) for agent(s)."""

    agents: Tuple[str, ...]
    tokens_in: float
    cache_read: float
    cost_usd: float

    @property
    def prompt_tokens(self) -> float:
        return self.tokens_in + self.cache_read


@dataclass
class EventDataset:
    """The extracted, calibratable view of the event stream."""

    provenance: Mapping[str, object]
    agents: Dict[str, AgentRunProfile]
    tasks: Dict[str, Mapping[str, float]]
    agent_dist: Dict[str, Quantiles]
    task_dist: Dict[str, Quantiles]
    per_event: Dict[str, Quantiles]
    op_profiles: Dict[str, OpProfile] = field(default_factory=dict)

    # -- lookups ----------------------------------------------------------
    def agent(self, name: str) -> Optional[AgentRunProfile]:
        return self.agents.get(name)

    def _pooled(self, metric: str) -> float:
        vals = [p.mean[metric] for p in self.agents.values()]
        return statistics.fmean(vals) if vals else 0.0

    def op_profile(self, op: str,
                   unit: str = "run") -> Optional[OpProfile]:
        """The calibrated profile for engine kind ``op`` (``None`` if unknown).

        ``unit="run"`` (default) prices an op as the mapped agents' mean real
        run; ``unit="event"`` prices it as their mean per recorded event row (the
        finer "one marginal operation" measure).
        """
        if unit == "run" and op in self.op_profiles:
            return self.op_profiles[op]
        return self._derive_op(op, unit=unit)

    def _derive_op(self, op: str, unit: str = "run") -> Optional[OpProfile]:
        agents = OP_AGENTS.get(op)
        if not agents:
            return None
        usable = [a for a in agents
                  if a in self.agents and self.agents[a].sessions >= MIN_SESSIONS]
        used = usable or list(agents)
        fallback = not usable
        per_row = unit == "event"

        def avg(metric: str) -> float:
            if per_row:
                vals = [self.agents[a].per_row(metric) for a in used
                        if a in self.agents]
            else:
                vals = [self.agents[a].mean[metric] for a in used
                        if a in self.agents]
            return statistics.fmean(vals) if vals else self._pooled(metric)

        in_tok, out_tok = avg("tokens_in"), avg("tokens_out")
        reasoning, cache = avg("tokens_reasoning"), avg("tokens_cache_read")
        seconds, tools = avg("active_ms") / 1000.0, avg("tool_calls")
        if op in PER_AC_OPS:
            in_tok /= PER_AC_DIVISOR
            out_tok /= PER_AC_DIVISOR
            reasoning /= PER_AC_DIVISOR
            cache /= PER_AC_DIVISOR
            seconds /= PER_AC_DIVISOR
            tools /= PER_AC_DIVISOR
        cost = llm_cost(in_tok, out_tok, reasoning, cache)
        cs_in = statistics.fmean(
            [self.agents[a].cold_start_in for a in used if a in self.agents]
        ) if any(a in self.agents for a in used) else self._pooled("tokens_in")
        cs_cache = statistics.fmean(
            [self.agents[a].cold_start_cache_read for a in used
             if a in self.agents]
        ) if any(a in self.agents for a in used) else self._pooled("tokens_cache_read")
        cs_cost = llm_cost(cs_in, 0.0, 0.0, cs_cache)
        return OpProfile(
            op=op, agents=tuple(used), in_tok=in_tok, out_tok=out_tok,
            reasoning_tok=reasoning, cache_read_tok=cache, cost_usd=cost,
            seconds=seconds, tool_calls=tools,
            cold_start_cost=cs_cost, cold_start_tokens=cs_in + cs_cache,
            fallback=fallback,
        )

    def cold_start(self, agents: Sequence[str]) -> ColdStart:
        """The pooled cold-start profile for a set of agents (system prompt)."""
        present = [self.agents[a] for a in agents if a in self.agents]
        if not present:
            return ColdStart(agents=tuple(agents), tokens_in=0.0,
                             cache_read=0.0, cost_usd=0.0)
        cs_in = statistics.fmean(p.cold_start_in for p in present)
        cs_cache = statistics.fmean(p.cold_start_cache_read for p in present)
        return ColdStart(
            agents=tuple(agents), tokens_in=cs_in, cache_read=cs_cache,
            cost_usd=llm_cost(cs_in, 0.0, 0.0, cs_cache),
        )

    # -- cost helper ------------------------------------------------------
    def op_cost(self, op: str) -> float:
        p = self.op_profile(op)
        return p.cost_usd if p is not None else 0.0


