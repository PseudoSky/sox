def load_events(source: str = EVENTS_SOURCE) -> List[dict]:
    """Load the event rows (read-only).  Raises if the source is absent."""
    with open(source, "r", encoding="utf-8") as fh:
        payload = json.load(fh)
    if "events" not in payload:
        raise ValueError(f"{source!r} is not an event stream (no 'events' key)")
    return payload["events"]


def _quantiles(values: Sequence[float]) -> Quantiles:
    vals = sorted(float(v) for v in values)
    if not vals:
        return Quantiles(p50=0.0)
    return Quantiles(
        p50=_quantile(vals, 0.50), p90=_quantile(vals, 0.90),
        mean=statistics.fmean(vals), count=len(vals),
    )


def _qrow(values: Sequence[float]) -> Dict[str, float]:
    """A JSON-serialisable ``{p50, p90, mean, count}`` row for the snapshot."""
    q = _quantiles(values)
    return {"p50": q.p50, "p90": q.p90 or 0.0, "mean": q.mean or 0.0,
            "count": q.count or 0}


def _quantile(sorted_vals: Sequence[float], p: float) -> float:
    n = len(sorted_vals)
    if n == 0:
        return 0.0
    k = (n - 1) * p
    f = int(math.floor(k))
    c = min(f + 1, n - 1)
    return sorted_vals[f] + (sorted_vals[c] - sorted_vals[f]) * (k - f)


def build_snapshot(events: Sequence[dict]) -> Dict[str, object]:
    """Extract the committed snapshot from raw event rows.

    This is the *only* place the extraction lives; :func:`extract` calls it and
    the committed ``events_snapshot.json`` is its output, so the committed data
    and a live re-extraction agree by construction.
    """
    # per (session, agent) -> summed metrics (one real agent run)
    runs: Dict[Tuple[str, str], Dict[str, float]] = {}
    for e in events:
        key = (e.get("session_id", ""), e.get("agent", ""))
        acc = runs.setdefault(key, {m: 0.0 for m in EVENT_METRICS})
        for m in EVENT_METRICS:
            acc[m] += float(e.get(m) or 0.0)

    by_agent: Dict[str, List[Dict[str, float]]] = {}
    for (_sid, agent), prof in runs.items():
        by_agent.setdefault(agent, []).append(prof)

    # cold start: the first event of each session (min t)
    first: Dict[str, dict] = {}
    for e in events:
        sid = e.get("session_id", "")
        cur = first.get(sid)
        if cur is None or e.get("t", 0) < cur.get("t", 0):
            first[sid] = e
    cold: Dict[str, List[dict]] = {}
    for e in first.values():
        cold.setdefault(e.get("agent", ""), []).append(e)

    rows_per_agent: Dict[str, int] = {}
    for e in events:
        a = e.get("agent", "")
        rows_per_agent[a] = rows_per_agent.get(a, 0) + 1

    agents: Dict[str, object] = {}
    for name, profiles in by_agent.items():
        if len(profiles) < MIN_SESSIONS:
            continue
        entry: Dict[str, object] = {"sessions": len(profiles),
                                    "rows": rows_per_agent.get(name, 0)}
        entry["mean"] = {m: statistics.fmean(p[m] for p in profiles)
                         for m in EVENT_METRICS}
        entry["median"] = {m: _quantile(sorted(p[m] for p in profiles), 0.50)
                           for m in EVENT_METRICS}
        entry["p90"] = {m: _quantile(sorted(p[m] for p in profiles), 0.90)
                        for m in EVENT_METRICS}
        cl = cold.get(name, [])
        entry["cold_start"] = {
            "n": len(cl),
            "in": statistics.fmean(e.get("tokens_in", 0) for e in cl) if cl else 0.0,
            "cache_read": (statistics.fmean(
                e.get("tokens_cache_read", 0) for e in cl) if cl else 0.0),
            "prompt": (statistics.fmean(
                (e.get("tokens_in", 0) + e.get("tokens_cache_read", 0))
                for e in cl) if cl else 0.0),
        }
        agents[name] = entry

    # per task: summed over all rows
    task_acc: Dict[str, Dict[str, float]] = {}
    for e in events:
        t = e.get("task", "")
        acc = task_acc.setdefault(
            t, {**{m: 0.0 for m in EVENT_METRICS}, "rows": 0.0})
        for m in EVENT_METRICS:
            acc[m] += float(e.get(m) or 0.0)
        acc["rows"] += 1.0
    top_tasks = sorted(task_acc.items(),
                       key=lambda kv: -kv[1]["cost_usd"])[:30]
    tasks = {
        t: {**{m: round(v[m], 6) for m in EVENT_METRICS}, "rows": int(v["rows"])}
        for t, v in top_tasks
    }

    # distributions
    agent_dist = {m: _qrow([sum(p[m] for p in lst)
                            for lst in by_agent.values()])
                  for m in EVENT_METRICS}
    task_dist = {m: _qrow([v[m] for v in task_acc.values()])
                 for m in EVENT_METRICS}
    per_event = {m: _qrow([e.get(m) or 0.0 for e in events])
                 for m in EVENT_METRICS}

    provenance = {
        "source": EVENTS_SOURCE,
        "schema_version": EVENT_SCHEMA_VERSION,
        "event_count": len(events),
        "total_cost_usd": round(sum(float(e.get("cost_usd") or 0.0)
                                    for e in events), 4),
        "total_dispatches": int(sum(e.get("dispatches") or 0 for e in events)),
        "total_steps": int(sum(e.get("steps") or 0 for e in events)),
        "total_tool_calls": int(sum(e.get("tool_calls") or 0 for e in events)),
        "window_start_ms": min((e.get("t", 0) for e in events), default=0),
        "window_end_ms": max((e.get("t", 0) for e in events), default=0),
        "span_days": round(
            (max((e.get("t", 0) for e in events), default=0)
             - min((e.get("t", 0) for e in events), default=0)) / 86_400_000.0, 2),
        "total_tokens": {
            m: int(sum(e.get(m) or 0 for e in events))
            for m in ("tokens_in", "tokens_out", "tokens_reasoning",
                      "tokens_cache_read", "tokens_cache_write")
        },
        "sum_result_chars": int(sum(e.get("result_chars") or 0 for e in events)),
        "sum_input_chars": int(sum(e.get("input_chars") or 0 for e in events)),
    }
    return {
        "provenance": provenance,
        "agents": agents,
        "tasks": tasks,
        "agent_dist": agent_dist,
        "task_dist": task_dist,
        "per_event": per_event,
    }


def dataset_from_snapshot(snapshot: Mapping[str, object]) -> EventDataset:
    """Build an :class:`EventDataset` from a snapshot mapping (no I/O)."""
    agents: Dict[str, AgentRunProfile] = {}
    for name, entry in snapshot["agents"].items():
        cs = entry.get("cold_start", {})  # type: ignore[union-attr]
        agents[name] = AgentRunProfile(
            agent=name,
            sessions=int(entry["sessions"]),  # type: ignore[index]
            mean=entry["mean"],  # type: ignore[index]
            median=entry["median"],  # type: ignore[index]
            p90=entry["p90"],  # type: ignore[index]
            cold_start_in=float(cs.get("in", 0.0)),
            cold_start_cache_read=float(cs.get("cache_read", 0.0)),
            cold_start_prompt=float(cs.get("prompt", 0.0)),
            cold_start_n=int(cs.get("n", 0)),
            rows=int(entry.get("rows", 0)),  # type: ignore[union-attr]
        )

    def _dist(group: Mapping[str, object]) -> Dict[str, Quantiles]:
        out: Dict[str, Quantiles] = {}
        for m, q in group.items():
            out[m] = Quantiles(
                p50=float(q["p50"]),  # type: ignore[index]
                p90=float(q["p90"]),  # type: ignore[index]
                mean=float(q["mean"]),  # type: ignore[index]
                count=int(q.get("count")) if q.get("count") is not None else None,  # type: ignore[union-attr]
            )
        return out

    ds = EventDataset(
        provenance=snapshot["provenance"],  # type: ignore[arg-type]
        agents=agents,
        tasks=snapshot["tasks"],  # type: ignore[arg-type]
        agent_dist=_dist(snapshot["agent_dist"]),  # type: ignore[arg-type]
        task_dist=_dist(snapshot["task_dist"]),  # type: ignore[arg-type]
        per_event=_dist(snapshot["per_event"]),  # type: ignore[arg-type]
    )
    ds.op_profiles = _derive_all_ops(ds)
    return ds


def _derive_all_ops(ds: EventDataset) -> Dict[str, OpProfile]:
    ops: Dict[str, OpProfile] = {}
    for op in OP_AGENTS:
        prof = ds._derive_op(op)
        if prof is not None:
            ops[op] = prof
    return ops


_SNAPSHOT_CACHE: Optional[EventDataset] = None


def snapshot_path() -> Path:
    return SNAPSHOT_PATH


def load_snapshot(path: Optional[Path] = None) -> Dict[str, object]:
    """Read the committed extraction snapshot (package data)."""
    with open(path or SNAPSHOT_PATH, "r", encoding="utf-8") as fh:
        return json.load(fh)


def dataset(path: Optional[Path] = None) -> EventDataset:
    """The committed event dataset (loaded once, memoised)."""
    global _SNAPSHOT_CACHE
    if _SNAPSHOT_CACHE is None:
        _SNAPSHOT_CACHE = dataset_from_snapshot(load_snapshot(path))
    return _SNAPSHOT_CACHE


def extract(source: str = EVENTS_SOURCE) -> EventDataset:
    """Re-extract the dataset from the raw source (read-only; for verification)."""
    return dataset_from_snapshot(build_snapshot(load_events(source)))


def source_available(source: str = EVENTS_SOURCE) -> bool:
    """True iff the raw event stream is present on this machine."""
    return Path(source).is_file()


