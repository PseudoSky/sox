"""pipeline_sim -- deterministic discrete-event simulation of an agentic
software-delivery pipeline.

This is a *simulation for design comparison*, not an operational scheduler.
Nothing here dispatches to production.

Model revision (spec 2026-10-05)
-------------------------------
* **Bucket** = a group of tickets (planning/assignment unit) -- NOT a merge
  unit.  **Merge structure** = an independent tree over ticket work units,
  parameterised by ``branch_levels`` / ``branch_fanout`` (spec 1.1, OPEN-8).
* A time model (``t_dispatch`` / ``t_op`` / ``t_suite`` / per-AC ``e``) and a
  cost model with a **compounding** high test term (``c_suite + sum(c_a)``).
* A ``test_level`` policy (``all`` | ``top`` | ``level:L``) expresses H1:
  deferring suite runs to higher merge levels (spec C10/C18).

Public surface
--------------
* :class:`~pipeline_sim.config.PipelineConfig` -- the full input ("theta").
* :func:`~pipeline_sim.engine.run` -- run one realisation.
* :func:`~pipeline_sim.harness.run_and_report` -- run + headline report.
* :func:`~pipeline_sim.harness.run_h1_contrast` -- the H1 contrast harness.
* :func:`~pipeline_sim.analytics.sqrt_bucket_size` -- the sqrt(M) batch law.
* :func:`~pipeline_sim.analytics.critical_path_bound` -- makespan lower bound.
"""

