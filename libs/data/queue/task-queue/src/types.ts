// @adhd/sox-task-queue — core types (SPEC §2-5)

// ─── TaskStatus ─────────────────────────────────────────────────────────────

export enum TaskStatus {
  Queued = 'queued',
  Running = 'running',
  Completed = 'completed',
  Failed = 'failed', // retries exhausted -> dead
  Cancelled = 'cancelled',
  Scheduled = 'scheduled', // waiting for scheduled_at to arrive
}

// ─── Task ────────────────────────────────────────────────────────────────────

export interface Task<T = unknown> {
  id: string; // UUIDv4, generated by enqueue if omitted
  type: string; // Logical task type for routing (e.g. 'reembed', 'email-send')
  status: TaskStatus;
  priority: number; // Higher = more urgent. Default: 0. Range: -128 to 127.
  payload: T; // Application-specific data. Must be JSON-serializable.
  retryCount: number; // Current retry attempt (0 = first execution)
  maxRetries: number; // 0 = no retries. Default: 3.
  scheduledAt: string | null; // ISO 8601. null = execute immediately on dequeue.
  created_at: string; // ISO 8601. Set at enqueue time.
  started_at: string | null; // ISO 8601. Set when a worker claims the task.
  completed_at: string | null; // ISO 8601. Set on complete or fail (terminal).
  error: string | null; // Last error message. null on success.
  dead: boolean; // true when maxRetries exhausted. Terminal.
  clientRequestId: string | null; // Idempotency key for dedup enqueue (see §7).
  result: string | null; // JSON-serialized result from the handler.
  leaseExpiresAt: string | null; // ISO 8601. Deadline for the current lease.
  workerId: string | null; // ID of the worker currently holding the lease.
  ttlMs: number | null; // Max wall-clock time before the task auto-fails.
}

// ─── TaskQueueConfig ─────────────────────────────────────────────────────────

export interface TaskQueueConfig {
  /** Path to the SQLite database file. ':memory:' is valid for testing. */
  dbPath: string;

  /** Maximum tasks to return in a single dequeue batch. Default: 10. */
  dequeueBatchSize?: number;

  /** Default maxRetries for tasks that don't specify one. Default: 3. */
  defaultMaxRetries?: number;

  /**
   * Heartbeat lease duration in milliseconds. The worker must heartbeat
   * within this window or the task is re-queued. Default: 30_000 (30s).
   */
  heartbeatTimeoutMs?: number;

  /**
   * Maximum wall-clock time before a task auto-fails. Overrides task-level
   * ttlMs. null = no global limit. Default: null.
   */
  defaultTtlMs?: number | null;

  /**
   * Whether to enable automatic re-queue of expired leases. When false,
   * expired tasks remain in 'running' state until manually resolved.
   * Default: true.
   */
  autoRequeueExpired?: boolean;

  /** Interval in milliseconds for the lease expiry reaper tick. Default: 5_000 (5s). */
  reaperIntervalMs?: number;

  /**
   * Maximum queue depth (count of queued+scheduled+running tasks) before
   * `enqueue`/`enqueueBatch` throw `QueueFullError`. 0 = unbounded.
   * Default: 0.
   *
   * Spec reconciliation: §2 omits this field from the `TaskQueueConfig`
   * code block, but D-8 in the decisions log names it explicitly
   * ("Optional per-queue maxDepth via config ... default: 0 = unbounded")
   * and §3's `enqueue` doc comment throws `QueueFullError` "if configured".
   * Added here so that documented behaviour is reachable.
   */
  maxQueueDepth?: number;

  /**
   * Called synchronously when a task transitions to dead (maxRetries
   * exhausted, via `fail()` or reaper lease-expiry). Must not throw --
   * errors are caught and logged at `warn` level.
   *
   * Spec reconciliation: named as a deferred spec-gap item in §13.5
   * ("Dead task alerting"). Implemented here as documented there.
   */
  onDead?: (task: Task) => void;
}

// ─── TaskFilter ──────────────────────────────────────────────────────────────

export interface TaskFilter {
  status?: TaskStatus | TaskStatus[];
  type?: string | string[];
  priorityMin?: number;
  priorityMax?: number;
  dead?: boolean;
  createdAfter?: string;
  createdBefore?: string;
  scheduledBefore?: string; // only tasks with scheduled_at <= this
  limit?: number;
  offset?: number;
  orderBy?: 'created_at' | 'priority' | 'scheduled_at';
  orderDir?: 'asc' | 'desc';
}

// ─── QueueStats ──────────────────────────────────────────────────────────────

export interface QueueStats {
  byStatus: Record<TaskStatus, number>;
  total: number;
  deadCount: number;
  runningCount: number;
  avgProcessingLatencyMs: number; // rolling average of completed - started
  retryDistribution: Record<number, number>; // retryCount -> count of live tasks
  oldestQueuedAgeMs: number; // age of the oldest 'queued' task
  heartbeatMisses: number; // count of tasks re-queued due to expired lease
  enqueueCount: number; // lifetime enqueues for this instance
  dequeueCount: number; // lifetime dequeues for this instance
  completeCount: number; // lifetime completions for this instance
  failCount: number; // lifetime terminal failures for this instance
}

