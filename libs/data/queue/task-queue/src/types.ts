// ─── TaskQueue — primary interface (SPEC §3) ─────────────────────────────────

export interface TaskQueue {
  // ── Lifecycle ───────────────────────────────────────────────────────────

  /** Open the database, apply schema, start the lease expiry reaper. Idempotent. */
  open(): Promise<void>;

  /**
   * Graceful shutdown: wait for in-flight tasks to complete (up to
   * drainTimeoutMs), then stop the reaper and close the database.
   * THROWS TaskTimeoutError if tasks are still running after drainTimeoutMs.
   */
  close(opts?: { drainTimeoutMs?: number }): Promise<void>;

  /** Returns true between open() and close(). */
  readonly isOpen: boolean;

  // ── Enqueue ──────────────────────────────────────────────────────────────

  enqueue(task: Partial<Task> & { type: string; payload: unknown }): Promise<EnqueueResult>;

  enqueueBatch(
    tasks: Array<Partial<Task> & { type: string; payload: unknown }>,
  ): Promise<EnqueueResult[]>;

  // ── Dequeue ──────────────────────────────────────────────────────────────

  dequeue(workerId: string): Promise<DequeueResult[]>;

  // ── Completion ───────────────────────────────────────────────────────────

  complete(taskId: string, result?: unknown): Promise<void>;

  fail(taskId: string, error: string): Promise<void>;

  // ── Heartbeat ────────────────────────────────────────────────────────────

  heartbeat(taskId: string): Promise<boolean>;

  // ── Cancellation ─────────────────────────────────────────────────────────

  cancel(taskId: string): Promise<boolean>;

  isCancelled(taskId: string): Promise<boolean>;

  // ── Query ────────────────────────────────────────────────────────────────

  get(taskId: string): Promise<Task | null>;

  listTasks(filter?: TaskFilter): Promise<Task[]>;

  stats(): Promise<QueueStats>;

  countTasks(filter?: TaskFilter): Promise<number>;

  // ── Admin / Maintenance ──────────────────────────────────────────────────

  purgeCompleted(olderThanMs: number): Promise<number>;

  requeue(taskId: string): Promise<void>;

  deleteTasks(filter: TaskFilter): Promise<number>;
}

// ─── Worker pool (SPEC §4) ───────────────────────────────────────────────────

export interface WorkerPoolConfig {
  queue: TaskQueue;

  handler: (task: Task) => Promise<void>;

  /** Maximum number of concurrent task executions. Default: 1. */
  concurrency?: number;

  /** Poll interval in milliseconds when no tasks are available. Default: 1_000 (1s). */
  pollIntervalMs?: number;

  /**
   * Heartbeat interval in milliseconds. Default: heartbeatTimeoutMs / 3.
   *
   * Spec reconciliation: the pool only has access to `queue` through the
   * `TaskQueue` interface, which does not expose `heartbeatTimeoutMs`. The
   * default here is 10_000ms (i.e. the queue's own 30_000ms default / 3).
   * If you configure a non-default `heartbeatTimeoutMs` on the queue, set
   * this explicitly to `heartbeatTimeoutMs / 3` to match.
   */
  heartbeatIntervalMs?: number;

  /** Maximum time in ms to wait for running handlers during graceful shutdown. Default: 30_000. */
  drainTimeoutMs?: number;

  /** Name for this worker pool instance (used as workerId in lease). Default: auto UUID. */
  workerName?: string;

  /** If true, the pool starts polling immediately. Default: true. */
  autoStart?: boolean;
}

export interface WorkerPool {
  start(): void;

  stop(): Promise<void>;

  readonly isRunning: boolean;

  readonly activeCount: number;

  readonly stats: {
    tasksProcessed: number;
    tasksFailed: number;
    tasksTimedOut: number;
  };
}

// ─── Scheduler (SPEC §5) ─────────────────────────────────────────────────────

export interface SchedulerConfig {
  queue: TaskQueue;

  /** Default task type for scheduled tasks. Default: 'scheduled'. */
  defaultType?: string;

  /** Default priority for scheduled tasks. Default: 0. */
  defaultPriority?: number;

  /** Default maxRetries for scheduled tasks. Default: 0 (no retries for cron tasks). */
  defaultMaxRetries?: number;

  /** Poll interval in ms for checking due cron expressions. Default: 1_000 (1s). */
  tickIntervalMs?: number;

  /** Auto-start the tick loop. Default: true. */
  autoStart?: boolean;

  /**
   * Path to the SQLite database file backing `scheduler_entries`.
   *
   * Spec reconciliation: §5's `SchedulerConfig` code block does not list a
   * `dbPath`, yet `Scheduler.open()`'s doc comment says "Open the scheduler
   * database" and §6 defines `scheduler_entries` in the same DDL block as
   * `tasks`. If omitted, the scheduler reuses the `dbPath` of the
   * `SqliteTaskQueue` passed as `queue` (read via its `dbPath` property) —
   * both open independent WAL-mode connections to the same file, which is
   * the exact pattern WAL was chosen for (see SPEC D-1).
   */
  dbPath?: string;
}

export interface ScheduledEntry {
  id: string; // UUIDv4, auto-generated
  name: string; // Human-readable label. Must be unique.
  taskType: string; // Task type for the enqueued task.
  payload: unknown; // Payload for the enqueued task. Must be JSON-serializable.
  cronExpression: string; // Standard cron syntax. Backend: croner.

  priority?: number;
  maxRetries?: number;
  ttlMs?: number | null;

  /**
   * If true, on scheduler start, the first enqueue immediately fires (even
   * if the cron would not have fired yet). Default: false.
   */
  runOnStart?: boolean;

  /** Whether this entry is active. Inactive entries are skipped on tick. Default: true. */
  enabled: boolean;

  created_at: string;
  updated_at: string;
  lastEnqueuedAt: string | null;
  lastError: string | null;
}

export interface Scheduler {
  open(): Promise<void>;

  close(): Promise<void>;

  register(
    entry: Omit<ScheduledEntry, 'id' | 'created_at' | 'updated_at' | 'lastEnqueuedAt' | 'lastError'>,
  ): Promise<ScheduledEntry>;

  update(id: string, entry: Partial<ScheduledEntry>): Promise<ScheduledEntry>;

  unregister(id: string): Promise<void>;

  enable(id: string, enabled: boolean): Promise<void>;

  get(id: string): Promise<ScheduledEntry | null>;

  list(): Promise<ScheduledEntry[]>;

  triggerNow(id: string): Promise<string>;

  readonly isRunning: boolean;
  readonly nextTickAt: string | null;
}
